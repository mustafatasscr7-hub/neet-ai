-- ncert_retrieval_log: one row per /chat answer that ran NCERT search (see _log_ncert_retrieval in
-- server.py). Chunk ids, scores and chapters only -- no question or answer text, no user id.
-- Safe to run before or after deploying; until it exists the server's inserts just fail silently.
-- Safe to re-run.
--
-- chunks: [{id, score, subject, class, chapter, used}] -- the chunks search_ncert returned (above
--   the similarity threshold), best first; used=false means the relevance check set it aside.
-- top_raw_score: the raw query's best similarity before any threshold/filter.
-- outcome: grounded (some chunks used) | set_aside (all chunks were another subject) | none.

create table if not exists public.ncert_retrieval_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  language text not null check (language in ('en', 'hi')),
  question_subject text,
  top_raw_score double precision,
  outcome text not null check (outcome in ('grounded', 'set_aside', 'none')),
  chunks jsonb not null default '[]'::jsonb
);
create index if not exists ncert_retrieval_log_created_at_idx on public.ncert_retrieval_log (created_at);

-- Internal telemetry: service-role only, same as answer_cache_log -- no anon/authenticated policy.
alter table public.ncert_retrieval_log enable row level security;

