-- answer_cache: versioned, language/style-keyed entries that expire, plus a hit/miss log.
-- Run this BEFORE deploying the matching server.py (2026-10-17 cost batch). Safe to re-run.
--
-- server.py now keys each entry on prompt version + language + answer style + the message text
-- (see _answer_cache_key), only for a chat's first message, and only serves rows that match the
-- current ANSWER_CACHE_PROMPT_VERSION and are under 30 days old. Rows written before this change
-- have no prompt_version, so they can never be served again -- cleanup_bad_answer_cache_rows.sql
-- deletes them.
--
-- Until this has been run, the new server code simply gets no cache hits and stores nothing (its
-- reads and writes fail and are treated as misses) -- it never errors.

-- 1. New columns on the cache itself (informational + used by the lookup filter).
alter table public.answer_cache add column if not exists prompt_version text;
alter table public.answer_cache add column if not exists language text;
alter table public.answer_cache add column if not exists answer_style text;

-- 2. Stores are upserts on question_hash (an expired row for the same key gets replaced), which
--    needs a unique index. There are no duplicate hashes today (checked 2026-10-17, 113 rows).
create unique index if not exists answer_cache_question_hash_key on public.answer_cache (question_hash);
-- For the 30-day retention delete (retention_cleanup.sql).
create index if not exists answer_cache_created_at_idx on public.answer_cache (created_at);

-- 3. One row per lookup (hit / miss / skip, with the skip reason: history, retry, media) and per
--    store decision (stored / not_stored, with the reason: clarifying, name, capped, corrected,
--    personalised, self_correction, ...). No user id and no message text -- just the question
--    hash, so repeat questions can be counted.
create table if not exists public.answer_cache_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event text not null check (event in ('hit', 'miss', 'skip', 'stored', 'not_stored')),
  reason text,
  question_hash text,
  prompt_version text,
  language text,
  answer_style text,
  is_guest boolean not null default false
);
create index if not exists answer_cache_log_created_at_idx on public.answer_cache_log (created_at);

-- Internal telemetry: service-role only, same as provider_usage_log -- no anon/authenticated policy.
alter table public.answer_cache_log enable row level security;

